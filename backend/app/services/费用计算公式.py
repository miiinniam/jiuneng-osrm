# ============================================================
# §6.2.1 重载速度惩罚 —— 载重比例（货重/车辆载重上限）越高，行驶越慢
# ============================================================
# 阈值必须按从小到大排列；最后一档用 float("inf") 兜底“超过前面所有阈值”的情况。
速度惩罚阈值表: list[tuple[float, float]] = [
    (0.5, 1.00),  # 载重比例 <= 0.5 （轻载）-> 正常速度
    (0.8, 1.15),  # 0.5 < 载重比例 <= 0.8 （中载）-> 慢 15%
    (float("inf"), 1.25),  # 载重比例 > 0.8 （重载）-> 慢 25%
]


def 速度系数(载重比例: float) -> float:
    for 阈值, 系数 in 速度惩罚阈值表:
        if 载重比例 <= 阈值:
            return 系数
    return 速度惩罚阈值表[-1][1]


# ============================================================
# §6.2.2 强制休息时间（越南交规估算值，非官方数值，仅供参考）
# ============================================================
每次连续驾驶小时数 = 4  # 每连续驾驶这么多小时，强制休息一次
每次强制休息小时数 = 0.5
单日过夜阈值小时数 = 8  # 调整后的行驶时长超过这个数，需要过夜休息
过夜休息小时数 = 8


def 休息时长(调整后行驶小时数: float) -> float:
    休息总时长 = 0.0
    剩余小时数 = 调整后行驶小时数
    while 剩余小时数 > 每次连续驾驶小时数:
        休息总时长 += 每次强制休息小时数
        剩余小时数 -= 每次连续驾驶小时数
    if 调整后行驶小时数 > 单日过夜阈值小时数:
        休息总时长 += 过夜休息小时数
    return 休息总时长


# ============================================================
# §6.2.3 装卸时间
# ============================================================
每吨装卸小时数 = 0.5


def 装卸时长(货物重量吨: float, 需要装卸: bool) -> float:
    return 货物重量吨 * 每吨装卸小时数 if 需要装卸 else 0.0


# ============================================================
# §6.2.4 总用时 —— 由上述各子项组装，正算和反算共用
# ============================================================
def 计算总用时(
    *,
    载重比例: float,
    原始行驶小时: float,
    货物重量吨: float,
    需要装卸: bool,
) -> tuple[float, float, float, float, float]:
    """组装完整的时间链，返回 (速度系数, 调整后行驶小时, 休息小时, 装卸小时, 总用时小时)。

    正算（cost_engine）和反算（calibration）都调用这个函数，
    保证两边对"一段行程需要多少时间"的计算逻辑完全一致。
    """
    sf = 速度系数(载重比例)
    adjusted = 原始行驶小时 * sf
    rest = 休息时长(adjusted)
    loading = 装卸时长(货物重量吨, 需要装卸)
    return sf, adjusted, rest, loading, adjusted + rest + loading


# ============================================================
# §6.3.0 拼货容量占比（仅拼货/consolidated 模式使用）
# ============================================================
def 容量占比(货物重量吨: float, 货物体积立方米: float | None,
             车型最大载重吨: float, 车型容积立方米: float | None) -> float:
    """拼货场景下，这批货占用了匹配车型的多大比例运力——按重量比和体积比取较大值
    （哪个先"装满"就按哪个算），车型没有容积上限（如平板车）时只看重量比。

    整车模式不调用这个函数，capacity_ratio 恒为 1.0，等价于本函数返回值恒为1的特例。
    """
    weight_ratio = 货物重量吨 / 车型最大载重吨 if 车型最大载重吨 else 0.0
    if 车型容积立方米 is None or 货物体积立方米 is None:
        return weight_ratio
    volume_ratio = 货物体积立方米 / 车型容积立方米 if 车型容积立方米 else 0.0
    return max(weight_ratio, volume_ratio)


# ============================================================
# §6.3.1 距离成本（基础运费）
# ============================================================
空车返回附加比例 = 0.5  # 空车返回时，返程按这个比例的距离成本计入


def 距离成本(距离公里: float, 车辆基础费率: float, 货物类型系数: float, 空车返回: bool) -> float:
    返程系数 = 空车返回附加比例 if 空车返回 else 0.0
    return 距离公里 * 车辆基础费率 * 货物类型系数 * (1 + 返程系数)


# ============================================================
# §6.3.2 时间成本
# ============================================================
def 时间成本(总用时小时数: float, 司机小时工资: float) -> float:
    return 总用时小时数 * 司机小时工资


# ============================================================
# §6.3.3 油耗成本（含载重油耗修正）
# ============================================================
油耗修正起始比例 = 0.5  # 载重比例超过这个值才开始增加油耗
油耗修正斜率 = 0.2  # 每超出 起始比例 1.0（即100%），油耗增加这个比例


def 油耗载重系数(载重比例: float) -> float:
    if 载重比例 <= 油耗修正起始比例:
        return 1.0
    return 1.0 + 油耗修正斜率 * (载重比例 - 油耗修正起始比例)


def 油耗成本(距离公里: float, 百公里油耗: float, 油价: float, 载重比例: float, 货物油耗附加比例: float) -> float:
    每公里油耗 = 百公里油耗 / 100
    return 距离公里 * 每公里油耗 * 油价 * 油耗载重系数(载重比例) * (1 + 货物油耗附加比例)


# ============================================================
# §6.3.4 固定费用
# ============================================================
def 装卸费(货物重量吨: float, 每吨装卸费率: float, 需要装卸: bool) -> float:
    return 货物重量吨 * 每吨装卸费率 if 需要装卸 else 0.0


def 保险费(货值: float | None, 保险费率: float) -> float:
    return 货值 * 保险费率 if 货值 else 0.0


def 路桥费(距离公里: float, 路桥费率: float) -> float:
    return 距离公里 * 路桥费率


def 车身附加费(车身固定附加费: float) -> float:
    """车身类型自带的固定附加费（比如冷链机组维护），跟距离/重量无关，每趟固定收一次。"""
    return 车身固定附加费


# ============================================================
# §6.3.4.1 港口目的地附加费（2026-07-16 新增）
# ============================================================
# 海防/广宁等港口区域有显著的额外成本（拥堵、特种装卸、单据费），
# 根据 2026-07-16 新供应商报价回归分析，港口溢价约为固定调度费的 75-85%。
# 没有固定调度费的车型（fixed_surcharge=0）视为该车型暂无港口数据，不追加港口费。
港口附加比例 = 0.75  # 港口目的地附加费 = 固定调度费 × 此比例


def 港口附加费(固定调度费: float, 是否港口目的地: bool) -> float:
    return 固定调度费 * 港口附加比例 if 是否港口目的地 and 固定调度费 > 0 else 0.0


# 以下三项路况附加费都是用户手动勾选触发（不是自动检测）——本地 OSRM 地图数据是静态提取的
# 越南地图，没有实时的限行/禁行、施工封闭、坡度数据源，没法自动判断路线是否经过这些路况。
# 三个基础金额是占位数字（参考装卸费 50000/吨、车身附加费 200000-250000 的量级），
# 不是市场调研数据，正式使用前需要人工核实调整。
# 2026-07-16: 以下三项占位值归零（v1.2）。原值为管理员手动估算（150K/150K/200K），
# 无供应商报价数据支撑，为避免虚假精度先设为 0。后续收集到市场数据后再恢复并校准。
禁限行绕行基础费_vnd = 0.0  # 原占位值 150K，2026-07-16 归零（待市场数据校准）
施工封闭绕行基础费_vnd = 0.0  # 原占位值 150K，2026-07-16 归零（待市场数据校准）
上坡山区附加基础费_vnd = 0.0  # 原占位值 200K，2026-07-16 归零（待市场数据校准）


def 禁限行绕行费(基础费: float, 类型系数: float, 需要绕开禁限行: bool) -> float:
    return 基础费 * 类型系数 if 需要绕开禁限行 else 0.0


def 施工封闭绕行费(基础费: float, 类型系数: float, 需要绕开施工封闭: bool) -> float:
    return 基础费 * 类型系数 if 需要绕开施工封闭 else 0.0


def 上坡山区附加费(基础费: float, 类型系数: float, 途经上坡山区: bool) -> float:
    return 基础费 * 类型系数 if 途经上坡山区 else 0.0


# ============================================================
# §6.3.5 整车总成本 —— 一口价模式，不拆分油耗/时间
# ============================================================
# 整车运输的报价逻辑与拼车不同：供应商报的是"一趟车从A到B总共多少钱"，
# 这个价格已经包含了距离/油耗/司机工资/路桥等全部成本。正算公式只需：
#   距离 × 基价（全包每公里费率）+ 各项附加费
# 不需要像拼车那样把油耗、时间、距离拆成三项分别计算。
#
# 基价每公里 来自 车辆型号库.csv 的 base_rate_vnd_per_km 列——
# 这个数字本身就是通过供应商真实报价反算出来的全包费率（见 calibration.py）。
def 整车总成本(
    *,
    距离公里: float,
    基价每公里: float,         # 从车辆型号库.csv 标定好的全包费率
    货物类型系数: float,
    空车返回: bool,
    路桥费_vnd: float,
    车身附加费_vnd: float,
    禁限行附加: float,
    施工封闭附加: float,
    上坡山区附加: float,
    港口附加: float,
    装卸费_vnd: float,
    保险费_vnd: float,
    杂费_vnd: float,
) -> float:
    return (
        距离成本(距离公里, 基价每公里, 货物类型系数, 空车返回)
        + 路桥费_vnd
        + 车身附加费_vnd
        + 禁限行附加
        + 施工封闭附加
        + 上坡山区附加
        + 港口附加
        + 装卸费_vnd
        + 保险费_vnd
        + 杂费_vnd
    )
